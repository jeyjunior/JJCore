using JJCore.Domain.Enums;
using JJCore.Domain.Interfaces.Repository;
using JJCore.Domain.Models;
using JJCore.Infra.Data.Extensions;
using System.Data;

namespace JJCore.Infra.Data.Infrastructure
{
    /// <summary>
    /// Base repository implementation that delegates generic CRUD operations to JJCore Dapper extensions.
    /// </summary>
    /// <typeparam name="TEntity">The mapped entity type.</typeparam>
    public abstract class Repository<TEntity> : IExtendedRepository<TEntity> where TEntity : class
    {
        /// <summary>
        /// Gets the unit of work used by this repository.
        /// </summary>
        protected readonly IUnitOfWork UnitOfWork;

        /// <summary>
        /// Creates a repository using the provided unit of work.
        /// </summary>
        /// <param name="unitOfWork">The unit of work that owns the connection and transaction.</param>
        public Repository(IUnitOfWork unitOfWork)
        {
            UnitOfWork = unitOfWork ?? throw new ArgumentNullException(nameof(unitOfWork));
        }

        /// <summary>
        /// Inserts one entity and returns its primary key as an integer.
        /// </summary>
        /// <param name="entity">The entity to insert.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The primary key converted to int.</returns>
        public virtual async Task<int> AddAsync(TEntity entity, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.AddAsync(entity, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Inserts one entity with cancellation support and returns its primary key as an integer.
        /// </summary>
        public virtual async Task<int> AddAsync(TEntity entity, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .AddAsync(entity, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Inserts one entity and returns its primary key without forcing an integer conversion.
        /// </summary>
        /// <param name="entity">The entity to insert.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The primary key generated by the database or assigned by the application.</returns>
        public virtual async Task<object?> AddReturningAsync(TEntity entity, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.AddReturningAsync(entity, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Inserts one entity with cancellation support and returns its primary key.
        /// </summary>
        public virtual async Task<object?> AddReturningAsync(TEntity entity, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .AddReturningAsync(entity, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Inserts multiple entities by executing the generated INSERT statement once per entity.
        /// </summary>
        /// <param name="entities">The entities to insert.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> AddBatchAsync(IEnumerable<TEntity> entities, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.AddBatchAsync(entities, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Inserts multiple entities with cancellation support.
        /// </summary>
        public virtual async Task<int> AddBatchAsync(IEnumerable<TEntity> entities, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .AddBatchAsync(entities, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Updates one entity using its mapped primary key.
        /// </summary>
        /// <param name="entity">The entity to update.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> UpdateAsync(TEntity entity, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.UpdateAsync(entity, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Updates one entity with cancellation support.
        /// </summary>
        public virtual async Task<int> UpdateAsync(TEntity entity, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .UpdateAsync(entity, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Deletes one entity by an integer primary key.
        /// </summary>
        /// <param name="id">The primary key value.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> DeleteAsync(int id, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Deletes one entity by an integer primary key with cancellation support.
        /// </summary>
        public virtual async Task<int> DeleteAsync(int id, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Deletes one entity by a long primary key.
        /// </summary>
        /// <param name="id">The primary key value.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> DeleteAsync(long id, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Deletes one entity by a long primary key with cancellation support.
        /// </summary>
        public virtual async Task<int> DeleteAsync(long id, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Deletes one entity by a primary key of any type, such as Guid or string.
        /// </summary>
        /// <param name="id">The primary key value.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> DeleteAsync(object id, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Deletes one entity by a primary key of any type with cancellation support.
        /// </summary>
        public virtual async Task<int> DeleteAsync(object id, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .DeleteAsync<TEntity>(id, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Deletes all rows from the mapped table.
        /// </summary>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> DeleteAllAsync(IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.DeleteAllAsync<TEntity>(transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Deletes all rows from the mapped table with cancellation support.
        /// </summary>
        public virtual async Task<int> DeleteAllAsync(IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .DeleteAllAsync<TEntity>(transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Executes a custom SQL command with optional parameters.
        /// </summary>
        /// <param name="query">The SQL command to execute.</param>
        /// <param name="parameters">The command parameters.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> ExecuteQueryAsync(string query, object? parameters = null, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.ExecuteQueryAsync(query, parameters, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Executes a custom SQL command with cancellation support.
        /// </summary>
        public virtual async Task<int> ExecuteQueryAsync(string query, object? parameters, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .ExecuteQueryAsync(query, parameters, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Executes a custom SQL command without parameters, with cancellation support.
        /// </summary>
        public virtual Task<int> ExecuteQueryAsync(string query, CancellationToken cancellationToken)
        {
            return ExecuteQueryAsync(query, null, null, cancellationToken);
        }

        /// <summary>
        /// Executes a custom SQL command that is sent without identifier translation.
        /// </summary>
        /// <param name="query">The SQL command to execute, written with native identifier quotes.</param>
        /// <param name="parameters">The command parameters.</param>
        /// <param name="transaction">The transaction to use, when provided.</param>
        /// <returns>The number of affected rows.</returns>
        public virtual async Task<int> ExecuteQueryAsync(RawSql query, object? parameters = null, IDbTransaction? transaction = null)
        {
            return await UnitOfWork.Connection.ExecuteQueryAsync(query, parameters, transaction ?? UnitOfWork.Transaction);
        }

        /// <summary>
        /// Executes a custom SQL command that is sent without identifier translation, with cancellation support.
        /// </summary>
        public virtual async Task<int> ExecuteQueryAsync(RawSql query, object? parameters, IDbTransaction? transaction, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .ExecuteQueryAsync(query, parameters, transaction ?? UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets one entity by its primary key value.
        /// </summary>
        /// <param name="id">The primary key value. String values are always treated as keys, never as SQL.</param>
        /// <returns>The entity when found; otherwise, null.</returns>
        public virtual Task<TEntity?> GetByIdAsync(object id)
        {
            return GetByIdAsync(id, CancellationToken.None);
        }

        /// <summary>
        /// Gets one entity by its primary key value with cancellation support.
        /// </summary>
        public virtual async Task<TEntity?> GetByIdAsync(object id, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetByIdAsync<TEntity>(id, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets one entity using a custom WHERE condition.
        /// </summary>
        /// <param name="condition">The SQL WHERE condition without the WHERE keyword.</param>
        /// <param name="parameters">The query parameters.</param>
        /// <returns>The entity when found; otherwise, null.</returns>
        public virtual Task<TEntity?> GetByConditionAsync(string condition, object? parameters = null)
        {
            return GetByConditionAsync(condition, parameters, CancellationToken.None);
        }

        /// <summary>
        /// Gets one entity using a custom WHERE condition with cancellation support.
        /// </summary>
        public virtual async Task<TEntity?> GetByConditionAsync(string condition, object? parameters, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetByConditionAsync<TEntity>(condition, parameters, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets one entity using a custom WHERE condition without parameters, with cancellation support.
        /// </summary>
        public virtual Task<TEntity?> GetByConditionAsync(string condition, CancellationToken cancellationToken)
        {
            return GetByConditionAsync(condition, null, cancellationToken);
        }

        /// <summary>
        /// Gets one entity using a WHERE condition that is sent without identifier translation.
        /// </summary>
        /// <param name="condition">The SQL WHERE condition without the WHERE keyword, written with native identifier quotes.</param>
        /// <param name="parameters">The query parameters.</param>
        /// <returns>The entity when found; otherwise, null.</returns>
        public virtual Task<TEntity?> GetByConditionAsync(RawSql condition, object? parameters = null)
        {
            return GetByConditionAsync(condition, parameters, CancellationToken.None);
        }

        /// <summary>
        /// Gets one entity using a WHERE condition that is sent without identifier translation, with cancellation support.
        /// </summary>
        public virtual async Task<TEntity?> GetByConditionAsync(RawSql condition, object? parameters, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetByConditionAsync<TEntity>(condition, parameters, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets one entity by its primary key value.
        /// </summary>
        [Obsolete(DapperExtensions.GetAsyncByIdObsoleteMessage)]
        public virtual Task<TEntity?> GetAsync(object id)
        {
            return GetByIdAsync(id);
        }

        /// <summary>
        /// Gets one entity by its primary key value with cancellation support.
        /// </summary>
        [Obsolete(DapperExtensions.GetAsyncByIdObsoleteMessage)]
        public virtual Task<TEntity?> GetAsync(object id, CancellationToken cancellationToken)
        {
            return GetByIdAsync(id, cancellationToken);
        }

        /// <summary>
        /// Gets one entity using a custom WHERE condition.
        /// </summary>
        [Obsolete(DapperExtensions.GetAsyncByConditionObsoleteMessage)]
        public virtual Task<TEntity?> GetAsync(string condition, object? parameters = null)
        {
            return GetByConditionAsync(condition, parameters);
        }

        /// <summary>
        /// Gets one entity using a custom WHERE condition with cancellation support.
        /// </summary>
        [Obsolete(DapperExtensions.GetAsyncByConditionObsoleteMessage)]
        public virtual Task<TEntity?> GetAsync(string condition, object? parameters, CancellationToken cancellationToken)
        {
            return GetByConditionAsync(condition, parameters, cancellationToken);
        }

        /// <summary>
        /// Gets a list of entities using an optional WHERE condition.
        /// </summary>
        /// <param name="condition">The SQL WHERE condition without the WHERE keyword.</param>
        /// <param name="parameters">The query parameters.</param>
        /// <returns>The matching entities.</returns>
        public virtual async Task<IEnumerable<TEntity>> GetListAsync(string condition = "", object? parameters = null)
        {
            return await UnitOfWork.Connection.GetListAsync<TEntity>(condition, parameters, UnitOfWork.Transaction);
        }

        /// <summary>
        /// Gets a list of entities using an optional WHERE condition with cancellation support.
        /// </summary>
        public virtual async Task<IEnumerable<TEntity>> GetListAsync(string condition, object? parameters, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetListAsync<TEntity>(condition, parameters, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets a list of entities using an optional WHERE condition without parameters, with cancellation support.
        /// </summary>
        public virtual Task<IEnumerable<TEntity>> GetListAsync(string condition, CancellationToken cancellationToken)
        {
            return GetListAsync(condition, null, cancellationToken);
        }

        /// <summary>
        /// Gets a list of entities using a WHERE condition that is sent without identifier translation.
        /// </summary>
        /// <param name="condition">The SQL WHERE condition without the WHERE keyword, written with native identifier quotes.</param>
        /// <param name="parameters">The query parameters.</param>
        /// <returns>The matching entities.</returns>
        public virtual Task<IEnumerable<TEntity>> GetListAsync(RawSql condition, object? parameters = null)
        {
            return GetListAsync(condition, parameters, CancellationToken.None);
        }

        /// <summary>
        /// Gets a list of entities using a WHERE condition that is sent without identifier translation, with cancellation support.
        /// </summary>
        public virtual async Task<IEnumerable<TEntity>> GetListAsync(RawSql condition, object? parameters, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetListAsync<TEntity>(condition, parameters, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets the next sequential code for a user-owned entity.
        /// </summary>
        /// <param name="userId">The user identifier used to scope the sequence.</param>
        /// <param name="initialValue">The first value to use when no rows exist.</param>
        /// <returns>The next available code. The value is not reserved atomically and can collide under concurrent calls.</returns>
        public virtual async Task<long> GetNextCodeAsync(long userId, long initialValue = 1)
        {
            return await UnitOfWork.Connection.GetNextCodeAsync<TEntity>(userId, initialValue, UnitOfWork.Transaction);
        }

        /// <summary>
        /// Gets the next sequential code for a user-owned entity with cancellation support.
        /// </summary>
        /// <returns>The next available code. The value is not reserved atomically and can collide under concurrent calls.</returns>
        public virtual async Task<long> GetNextCodeAsync(long userId, long initialValue, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetNextCodeAsync<TEntity>(userId, initialValue, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets all entities owned by one user.
        /// </summary>
        /// <param name="userId">The user identifier.</param>
        /// <returns>The matching entities.</returns>
        public virtual async Task<IEnumerable<TEntity>> GetListByUserAsync(long userId)
        {
            return await UnitOfWork.Connection.GetListByUserAsync<TEntity>(userId, UnitOfWork.Transaction);
        }

        /// <summary>
        /// Gets all entities owned by one user with cancellation support.
        /// </summary>
        public virtual async Task<IEnumerable<TEntity>> GetListByUserAsync(long userId, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetListByUserAsync<TEntity>(userId, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets one user-owned entity by its per-user code.
        /// </summary>
        /// <param name="code">The per-user code value.</param>
        /// <param name="userId">The user identifier.</param>
        /// <returns>The entity when found; otherwise, null.</returns>
        public virtual async Task<TEntity?> GetByCodeAsync(long code, long userId)
        {
            return await UnitOfWork.Connection.GetByCodeAsync<TEntity>(code, userId, UnitOfWork.Transaction);
        }

        /// <summary>
        /// Gets one user-owned entity by its per-user code with cancellation support.
        /// </summary>
        public virtual async Task<TEntity?> GetByCodeAsync(long code, long userId, CancellationToken cancellationToken)
        {
            return await UnitOfWork.Connection
                .GetByCodeAsync<TEntity>(code, userId, UnitOfWork.Transaction, cancellationToken)
                .ConfigureAwait(false);
        }

        /// <summary>
        /// Gets the database provider currently used by the repository connection.
        /// </summary>
        public DatabaseType ActiveDatabase => UnitOfWork.Connection.IdentifyDatabase();
    }
}
